// editsCss.js — the editor's style model, and the one file it becomes
//
// Shared by the editor's server (which writes src/styles/edits.css on save)
// and its client (which previews the same text live inside the site). One
// generator, so what you see while editing is byte-for-byte what is saved.
//
// THE MODEL
//   { rules: { [selector]: { base: {prop: value}, "860": {...}, "560": {...} } } }
//
// Three buckets, because site.css has exactly two breakpoints (860 and 560 px)
// and a change made at a larger size must carry down to the smaller ones until
// it is changed there. `base` is written with no media query, so it applies at
// every width; the other two are max-width queries written AFTER it, so they
// win below their width. That is the whole cascade, and it is plain CSS.
//
// WHY THE FILE IS PARSED BACK RATHER THAN KEPT BESIDE A JSON COPY: one file is
// one source of truth. The format below is regular on purpose (one rule per
// line, inside three marked sections), so reading it back is a few regexes and
// a person can still read it in a diff.

export const BPS = [
  { key: "base", label: "Desktop", query: null,                   width: 1512 },
  { key: "860",  label: "Tablet",  query: "(max-width:860px)",    width: 768 },
  { key: "560",  label: "Phone",   query: "(max-width:560px)",    width: 390 }
];

const HEADER = `/* edits.css — GENERATED BY THE EDITOR. Do not edit by hand.

   Written by \`npm run edit\` (editor/) every time Save is pressed, and read
   back by it on load, so a hand edit here is overwritten by the next save
   unless it keeps this exact format. It is imported AFTER site.css in
   main.js and every selector starts at #doc, so a rule here wins over the
   stylesheet it is correcting.

   Three sections: every width, then tablet (<=860 px), then phone (<=560 px).
   A change made at a larger size applies to the smaller ones until it is
   changed there, which is the order the sections are written in. After them,
   up to three "@hide" sections: an element hidden on exactly one device's
   width range (desktop, tablet or phone), which does not cascade.

   [data-e="..."] is an id the editor wrote into the element's own markup;
   #doc[data-page="..."] scopes a rule to one page (site/router.js sets it). */
`;

export const emptyModel = () => ({ rules: {}, hide: {} });

// ── WHO CAN SEE IT ──────────────────────────────────────────────────────────
// The three buckets above CASCADE DOWN: a value set on Desktop is in force on
// Tablet and Phone until one of them changes it. That is right for a size or a
// position and wrong for "is it there", which was the trap: the only control
// was `display:none` in a bucket, so hiding a paragraph on Desktop hid it on
// the phone too, and there was no value to write at Phone that meant "shown
// again" (that would be the element's own display -- flex, block, inline --
// which the editor cannot know). A paragraph written for the phone could be
// made, but not shown on the phone and hidden on the laptop.
//
// So visibility is not a bucket. It is a set of devices the element is hidden
// on, and each device is its OWN width range, which never cascades:
//     Desktop  (min-width:861px)
//     Tablet   (min-width:561px) and (max-width:860px)
//     Phone    (max-width:560px)
// each written as a plain `display:none` under exactly that query, in a
// section after the buckets so it wins. Nothing has to know an element's
// natural display, because "shown" is simply the absence of a rule.
export const DEVICES = [
  { key: "d", bp: "base", label: "Desktop", query: "(min-width:861px)" },
  { key: "t", bp: "860",  label: "Tablet",  query: "(min-width:561px) and (max-width:860px)" },
  { key: "p", bp: "560",  label: "Phone",   query: "(max-width:560px)" }
];
export const deviceOf = (bp) => DEVICES.find((d) => d.bp === bp).key;

/** one declaration block, in a stable order so a diff only shows real change */
function block(decls) {
  return Object.keys(decls).sort()
    .map((p) => `${p}:${decls[p]};`).join(" ");
}

export function toCss(model) {
  const out = [HEADER];
  for (const bp of BPS) {
    const lines = [];
    for (const sel of Object.keys(model.rules).sort()) {
      const d = model.rules[sel][bp.key];
      if (d && Object.keys(d).length) lines.push(`${sel} { ${block(d)} }`);
    }
    if (bp.query) {
      out.push(`/* @bp ${bp.key} */\n@media ${bp.query} {\n${lines.map((l) => "  " + l).join("\n")}\n}\n`);
    } else {
      out.push(`/* @bp base */\n${lines.join("\n")}\n`);
    }
  }
  // who can see it: after everything else, so a hide always wins
  const hide = model.hide || {};
  for (const dev of DEVICES) {
    const lines = Object.keys(hide).sort().filter((sel) => hide[sel][dev.key]).map((sel) => `${sel} { display:none; }`);
    if (lines.length) out.push(`/* @hide ${dev.key} */\n@media ${dev.query} {\n${lines.map((l) => "  " + l).join("\n")}\n}\n`);
  }
  return out.join("\n");
}

/** parse a declaration list, respecting parentheses and quotes */
function decls(body) {
  const d = {};
  let depth = 0, q = "", cur = "";
  const flush = () => {
    const i = cur.indexOf(":");
    if (i > 0) d[cur.slice(0, i).trim()] = cur.slice(i + 1).trim();
    cur = "";
  };
  for (const ch of body) {
    if (q) { cur += ch; if (ch === q) q = ""; continue; }
    if (ch === '"' || ch === "'") { q = ch; cur += ch; continue; }
    if (ch === "(") depth++;
    if (ch === ")") depth--;
    if (ch === ";" && depth === 0) { flush(); continue; }
    cur += ch;
  }
  if (cur.trim()) flush();
  return d;
}

export function fromCss(text) {
  const model = emptyModel();
  if (!text) return model;
  // the hide sections come last; take them off before the buckets are read,
  // or the phone bucket would swallow them
  const at = text.search(/\/\* @hide [dtp] \*\//);
  if (at >= 0) {
    for (const sec of text.slice(at).split(/\/\* @hide ([dtp]) \*\//).slice(1).reduce((a, x, i, all) => (i % 2 ? a : [...a, [x, all[i + 1]]]), [])) {
      for (const m of sec[1].matchAll(/([^{}\n][^{}]*?)\s*\{\s*display:\s*none;?\s*\}/g)) {
        const sel = m[1].trim();
        if (sel && !sel.startsWith("@") && !sel.startsWith("/*")) ((model.hide[sel] ||= {})[sec[0]] = true);
      }
    }
    text = text.slice(0, at);
  }
  const parts = text.split(/\/\* @bp (base|860|560) \*\//);
  for (let i = 1; i < parts.length; i += 2) {
    const key = parts[i];
    let body = parts[i + 1];
    if (key !== "base") {
      const a = body.indexOf("{"), b = body.lastIndexOf("}");
      body = a >= 0 && b > a ? body.slice(a + 1, b) : "";
    }
    // a rule is `selector { decls }` on one line; selectors never contain a
    // brace, and the editor never writes a declaration that does
    for (const m of body.matchAll(/([^{}\n][^{}]*?)\s*\{([^{}]*)\}/g)) {
      const sel = m[1].trim();
      if (!sel || sel.startsWith("/*")) continue;
      (model.rules[sel] ||= {})[key] = decls(m[2]);
    }
  }
  return model;
}

/** the value in force at a breakpoint, with where it came from */
export function effective(model, sel, bpKey, prop) {
  const r = model.rules[sel];
  if (!r) return { value: undefined, from: null };
  const order = BPS.map((b) => b.key);
  for (let i = order.indexOf(bpKey); i >= 0; i--) {
    const v = r[order[i]]?.[prop];
    if (v !== undefined) return { value: v, from: order[i] };
  }
  return { value: undefined, from: null };
}

export function setProp(model, sel, bpKey, prop, value) {
  const r = (model.rules[sel] ||= {});
  const d = (r[bpKey] ||= {});
  if (value === undefined || value === null || value === "") delete d[prop];
  else d[prop] = value;
  if (!Object.keys(d).length) delete r[bpKey];
  if (!Object.keys(r).length) delete model.rules[sel];
}

/** for each device: is the element hidden there, by a bucket's old `display:none` or by a hide range? */
export function hiddenOn(model, sel) {
  const out = {};
  for (const d of DEVICES) {
    out[d.key] = effective(model, sel, d.bp, "display").value === "none" || !!model.hide?.[sel]?.[d.key];
  }
  return out;
}

/**
 * Hide the element on exactly these devices (`want` is { d, t, p } of booleans
 * meaning HIDDEN). A `display:none` an older version of the editor wrote into
 * a bucket is folded in here, so one element never has two ways of being hidden.
 */
export function setHidden(model, sel, want) {
  for (const d of DEVICES) if (model.rules[sel]?.[d.bp]?.display === "none") setProp(model, sel, d.bp, "display", null);
  const h = (model.hide ||= {});
  if (want.d || want.t || want.p) h[sel] = { d: !!want.d, t: !!want.t, p: !!want.p };
  else delete h[sel];
}

export const clone = (m) => JSON.parse(JSON.stringify(m));
